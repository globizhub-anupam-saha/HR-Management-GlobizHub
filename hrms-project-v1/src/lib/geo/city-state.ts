/**
 * Returns states for a given country code
 */
export function getStatesByCountry(countryCode: string = "IN"): string[] {
  const country = STATES_AND_CITIES[countryCode];
  if (!country) return [];
  return Object.keys(country).sort((a, b) => a.localeCompare(b));
}

/**
 * Returns cities for a given country and state
 */
export function getCitiesByState(countryCode: string = "IN", stateName: string): string[] {
  const country = STATES_AND_CITIES[countryCode];
  if (!country || !stateName) return [];
  const cities = country[stateName];
  if (!cities) return [];
  return [...cities];
}

/**
 * Fast search across all cities with city, state, country metadata
 */
export function searchCities(query: string, maxResults: number = 10): CityResult[] {
  const clean = query.trim().toLowerCase();
  if (!clean || clean.length < 2) return [];

  const results: CityResult[] = [];

  for (const [countryCode, states] of Object.entries(STATES_AND_CITIES)) {
    const countryObj = COUNTRIES.find((c) => c.code === countryCode);
    const countryName = countryObj ? countryObj.name : countryCode;

    for (const [stateName, cities] of Object.entries(states)) {
      for (const city of cities) {
        if (
          city.toLowerCase().includes(clean) ||
          stateName.toLowerCase().includes(clean)
        ) {
          results.push({
            city,
            state: stateName,
            country: countryName,
            countryCode,
          });
          if (results.length >= maxResults) return results;
        }
      }
    }
  }

  return results;
}

